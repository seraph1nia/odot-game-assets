"""Bind fresh native palette campaign/captures and an actually loaded current ZIP."""
import hashlib
import json
from pathlib import Path

from tools.asset_catalog.ui_assets import package_bytes, payload_files

ROOT = Path(__file__).resolve().parents[2]
DOCS = ROOT / 'docs/ui'


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    historical = ROOT / 'docs/vivid-palette/ui-before-validation.json'
    binding = json.loads(historical.read_text())
    results_path = DOCS / 'production/vivid-palette-explicit/results.json'
    result = json.loads(results_path.read_text())
    payload = json.loads((DOCS / 'payload.json').read_text())
    package = json.loads((DOCS / 'catalog/package-check.json').read_text())
    previews = json.loads((DOCS / 'catalog/previews.json').read_text())
    assert not result['failures'] and result['checks'] == 3626
    current = hashlib.sha256(package_bytes(ROOT, payload_files(ROOT))).hexdigest()
    assert package['package_sha256'] == current
    assert package['files'] == {'UI/' + p: h for p, h in payload['files'].items()}
    for name, value in result['source_sha256'].items():
        assert sha(ROOT / 'ui/preview' / name) == value, name
    binding.update(scope='Vivid six-SVG palette recovery only; native APIs/layout/alpha/seal retained; standalone asset evidence, not game acceptance',
                   results=results_path.relative_to(DOCS).as_posix(), results_sha256=sha(results_path),
                   checks=result['checks'], capture_count=len(result['captures']),
                   capture_sha256={item['path']: sha(results_path.parent / item['path']) for item in result['captures']},
                   renderer=result['renderer'], runtime_files={p: payload['files'][p] for p in binding['runtime_files']},
                   art_provenance_sha256=sha(DOCS / binding['art_provenance']),
                   package_sha256=current, directly_tested_package_sha256=current,
                   package_check_sha256=sha(DOCS / 'catalog/package-check.json'),
                   catalog_sha256={k: row['sha256'] for k, row in previews['entries'].items()},
                   package_proof='Freshly rebuilt current catalog ZIP directly loaded in an independent native UI-only project; exact archive/member hashes checked against current generated bytes. Earlier existing dist ZIP load was stale and is not current qualification.')
    binding['qualification_status'].update(submitted_receipts='Prior grey palette campaign preserved verbatim in docs/vivid-palette/ui-before-validation.json; no historical result rebinding',
        review_focused_results=binding['results'], review_failed_attempt='../vivid-palette/ui-import-failure.json',
        current_acceptance='Current source-bound standalone native campaign: 3626 checks/121 captures, fourteen fresh native catalog images and independent current-payload/current-ZIP load. Software Mesa/Xvfb; no actual-game/GPU/artist acceptance.')
    binding['tools_sha256'] = {p: sha(ROOT / p) for p in binding['tools_sha256']}
    binding['footprint']['total_payload_bytes'] = payload['total_file_bytes']
    binding['payload_audit'].update(files=len(payload['files']), scenes=sum(p.endswith('.tscn') for p in payload['files']), log=payload['log'])
    binding['review'] = {'method': 'Current native palette captures plus full 3D actual comparisons; mechanical evidence is separate from visual judgment.',
                          'images': [], 'historical_binding': '../vivid-palette/ui-before-validation.json',
                          'historical_binding_sha256': sha(historical),
                          'judgment': 'Current catalog HUD and Worldtree captures visually inspected for recovered parchment/leaf/violet hues and retained readability. Full stage/size/transition artistic acceptance is not claimed.',
                          'limits': '121 current campaign captures are mechanically checked, not individually artist-approved; historical review does not transfer to changed pixels.'}
    (DOCS / 'worldtree-validation.json').write_text(json.dumps(binding, indent=2) + '\n')
    print('Bound fresh current native campaign, catalog and directly loaded ZIP:', current)


if __name__ == '__main__':
    main()
